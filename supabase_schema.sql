-- Klaro multi-tenant schema for Supabase Postgres (Phase 7.1).
-- Run ONCE in the Supabase SQL Editor on a fresh project. Idempotent where
-- practical so re-running is safe.
--
-- Tenancy model:
--   • Every user-owned row carries user_id -> auth.users(id).
--   • RLS restricts direct (PostgREST / anon-key) access to the owner's rows.
--   • The FastAPI service connects as the table owner (postgres), which is not
--     subject to RLS, and ALSO filters every query by the authenticated
--     user_id (belt-and-suspenders). RLS is the backstop for any access that
--     does not go through the trusted API.

-- ─────────────────────────── expenses ───────────────────────────
create table if not exists public.expenses (
    id            bigint generated by default as identity primary key,
    user_id       uuid not null references auth.users(id) on delete cascade,
    merchant      varchar(255) not null,
    amount        double precision not null,
    date          timestamptz not null,
    raw_sms       text default '',
    raw_sms_hash  varchar(64),
    upi_id        varchar(255),
    is_labeled    boolean default true,
    category      varchar(100),
    method        varchar(20) default 'upi',
    direction     varchar(10) not null default 'debit',
    created_at    timestamptz default now()
);
create index if not exists ix_expenses_user on public.expenses(user_id);
create index if not exists ix_expenses_user_hash on public.expenses(user_id, raw_sms_hash);
create index if not exists ix_expenses_user_dir on public.expenses(user_id, direction);

-- ─────────────────────────── budgets ───────────────────────────
create table if not exists public.budgets (
    user_id     uuid not null references auth.users(id) on delete cascade,
    category    varchar(100) not null,         -- a category, or 'overall'
    amount      double precision not null,
    updated_at  timestamptz default now(),
    primary key (user_id, category)
);

-- ──────────────────── merchant_categories ──────────────────────
create table if not exists public.merchant_categories (
    user_id          uuid not null references auth.users(id) on delete cascade,
    merchant_norm    varchar(255) not null,
    merchant_display varchar(255) not null,
    category         varchar(100) not null,
    source           varchar(20) default 'user',  -- user|ai|brand|keyword
    updated_at       timestamptz default now(),
    primary key (user_id, merchant_norm)
);

-- ──────────────────── recurring_dismissals ─────────────────────
create table if not exists public.recurring_dismissals (
    user_id          uuid not null references auth.users(id) on delete cascade,
    merchant_norm    varchar(255) not null,
    merchant_display varchar(255) not null,
    created_at       timestamptz default now(),
    primary key (user_id, merchant_norm)
);

-- ─────────────────────────── RLS ───────────────────────────────
-- Enable (not FORCE) so the table owner the API connects as is unaffected,
-- while anon/authenticated access via PostgREST is restricted to own rows.
-- Re-runnable: policies are dropped first.
do $$
declare t text;
begin
  foreach t in array array['expenses','budgets','merchant_categories','recurring_dismissals']
  loop
    execute format('alter table public.%I enable row level security;', t);
    execute format('drop policy if exists %I on public.%I;', t||'_owner', t);
    execute format(
      'create policy %I on public.%I using (user_id = auth.uid()) with check (user_id = auth.uid());',
      t||'_owner', t);
  end loop;
end $$;
